"""Personal techniques awarded by specific books. Battle rules use the shared event engine."""

from dataclasses import dataclass

from .trait_rule_builders import ATTACK, DEFEND, HIT, ONCE, Signature, adjust, fact, modify, rule, status


@dataclass(frozen=True)
class Repertoire:
    name: str
    family: str
    book: str
    signature: Signature
    artifact: str = ""
    bodily: bool = False


def form(name, family, book, text, *rules, artifact="", bodily=False):
    delayed = any(
        action.get("consume_on") and action.get("delay") == 1 and action["duration"] == 2
        for step in rules
        for action in step["actions"]
    )
    if delayed and "两轮" not in text:
        text += "后续一次性招式须在随后两轮内用出。"
    return Repertoire(name, family, "TECH_" + book, Signature(text, rules), artifact, bodily)


def together(*conditions):
    return {"all": list(conditions)}


FIRST = fact("event.first", "eq", True)
LAST = fact("event.first", "eq", False)
HURT = together(DEFEND, fact("event.actual_loss", "gt", 0))
STRUCK = fact("self.ordinary_dealt", "gt", 0)
WOUNDED = fact("self.ordinary_received", "gt", 0)
UNHURT = fact("self.ordinary_received", "eq", 0)
MISSED = fact("self.ordinary_dealt", "eq", 0)
SHORT = fact("event.short_debuff", "eq", True)
CLEANSE = {"op": "dispel_short_debuff"}
START, END = "round_start", "round_end"
READY, ORDER = "ordinary_start", "initiative_resolved"
BEFORE, AFTER = "ordinary_before_damage", "ordinary_after_damage"
OPENING = {"start": 1, "end": 1}


def shift(stat, value):
    return modify("ordinary." + stat, value)


def next_use(name, stat, value, *, delay=1, duration=2, enemy=False, bound=False):
    damage = stat in {"dealt", "received", "received_cap"}
    return status(
        name,
        "ordinary." + stat,
        value,
        duration,
        delay=delay,
        consume_on=BEFORE if damage else READY,
        bind_target=bound,
        recipient="target" if enemy else "self",
        dispellable=enemy and (value > 0 if stat == "received" else value < 0),
    )


def bank(token, capacity=1):
    return dict(op="counter_add", key=token, value=1, max=capacity)


def spend(token, count=1):
    return dict(op="counter_consume", key=token, value=count)


