"""Promote reviewed bitmap studies into self-contained, ownership-aware runtime assets."""
import argparse
import hashlib
import json
import shutil
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--icons', type=Path, default=ROOT/'design/inventory-icons-v15-20261020/combined-catalog.json')
    parser.add_argument('--maps', type=Path, default=ROOT/'design/ten-realms-atlas-20261020')
    args = parser.parse_args()
    icons = json.loads(args.icons.read_text(encoding='utf-8'))
    base_items = json.loads((ROOT/'content/items.json').read_text(encoding='utf-8'))['items']
    item_owners = {row['id']:None for row in base_items}
    packages = {}
    for path in sorted((ROOT/'dlc').glob('*/manifest.json')):
        manifest = json.loads(path.read_text(encoding='utf-8'))
        packages[manifest['id']] = path.parent
        items = path.parent/'content/items.json'
        if items.is_file():
            for row in json.loads(items.read_text(encoding='utf-8')).get('items',[]):
                item_owners.setdefault(row['id'],manifest['id'])
        pools = path.parent/'content/guixu_tide.json'
        if pools.is_file():
            private = {row['content_id'] for dungeon in json.loads(pools.read_text(encoding='utf-8'))['dungeons']
                       for row in dungeon['treasure_pool'] if row.get('exclusive_source') == 'guixu_tide'}
            # Definition location does not override the authoritative exclusive source.
            for row in base_items:
                if row['id'] in private or row.get('technique_id') in private:
                    item_owners[row['id']] = manifest['id']
    # Secret-art materials are generated by the base module, not an optional DLC.
    uses = defaultdict(list)
    for item_id, asset_id in icons['owned_icon_map'].items():
        uses[asset_id].append(item_owners.get(item_id))
    catalog = dict(schema_version=1,assets={},items={},molds={},plants={},crafting_materials={},maps={})
    for asset in icons['assets']:
        identity = asset['id']
        owners = set(uses.get(identity,[None]))
        requirement = sorted(owner for owner in owners if owner) if None not in owners else []
        if len(requirement) == 1:
            relative = f"visual/icons/{identity}.png"
            target = packages[requirement[0]]/'assets'/relative
            url = f'/extension-assets/{requirement[0]}/{relative}'
            previous = (ROOT/f'web/assets/pixel/v2/icons/{identity}.png').resolve()
            owned_root = (ROOT/'web/assets/pixel/v2/icons').resolve()
            if previous.is_file():
                assert previous.is_relative_to(owned_root)
                source = (ROOT/'design/inventory-icons-v1-20261020'/asset['file']).resolve()
                assert previous.read_bytes() == source.read_bytes(), 'Do not remove an independently edited asset'
                previous.unlink()
        else:
            target = ROOT/f'web/assets/pixel/v2/icons/{identity}.png'
            url = f'/assets/pixel/v2/icons/{identity}.png'
            requirement = []
        target.parent.mkdir(parents=True,exist_ok=True)
        source = (ROOT/'design/inventory-icons-v1-20261020'/asset['file']).resolve()
        shutil.copy2(source,target)
        catalog['assets'][identity] = dict(file=url,size=[32,32],sha256=hashlib.sha256(target.read_bytes()).hexdigest(),requires=requirement)
        if asset.get('mold_id'):
            catalog['molds'][asset['mold_id']] = identity
        definition = asset.get('definition',{})
        for kind, group in [('plant','plants'),('crafting_material','crafting_materials')]:
            if definition.get('kind') == kind:
                catalog[group][definition['id']] = identity
    for item_id, asset_id in icons['owned_icon_map'].items():
        owner = item_owners.get(item_id)
        catalog['items'][item_id] = dict(asset=asset_id,requires=[owner] if owner else [])
    raw = (args.maps/'data.js').read_text(encoding='utf-8')
    worlds = json.loads(raw[raw.index('=')+1:].strip().removesuffix(';'))['worlds']
    for world in worlds:
        identity = 'map.'+world['id']
        target = ROOT/f"web/assets/pixel/v2/maps/{world['id']}.png"
        target.parent.mkdir(parents=True,exist_ok=True)
        # Keep the reviewed 768px logical image, not repeated upscaled pixels.
        source = args.maps/'maps'/world['id']/'logical.png'
        shutil.copy2(source,target)
        catalog['assets'][identity] = dict(file=f'/assets/pixel/v2/maps/{world["id"]}.png',size=[768,576],
            sha256=hashlib.sha256(target.read_bytes()).hexdigest(),requires=[])
        catalog['maps'][world['id']] = dict(asset=identity,places={p['id']:{k:p[k] for k in ['x','y','major']} for p in world['places']})
    # Independently promoted DLC character packs survive an icon/map re-export.
    for owner,package in packages.items():
        for path in (package/'assets/visual').glob('*/registry.json'):
            for key,row in json.loads(path.read_text(encoding='utf-8'))['assets'].items():
                assert row['requires']==[owner] and row['file'].startswith(f'/extension-assets/{owner}/')
                assert key not in catalog['assets'], key
                target=package/'assets'/row['file'].split('/',3)[3]
                assert target.resolve().is_relative_to((package/'assets').resolve())
                assert hashlib.sha256(target.read_bytes()).hexdigest()==row['sha256']
                catalog['assets'][key]=row
    (ROOT/'content/visual_assets.json').write_text(json.dumps(catalog,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    print(f"Promoted {len(icons['assets'])} icons and {len(worlds)} maps; source studies remain unchanged.")


if __name__ == '__main__':
    main()
